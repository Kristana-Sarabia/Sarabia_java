package aug10;

public class Countdown {

	public static void main(String[] args) {
		int a = 10;
		
		System.out.println("Initial Value: "+a);
		System.out.println("Post-decrement: "+(a--));
		System.out.println("After post-decrement: "+a);
		System.out.println("Post-decrement: "+(a--));
		System.out.println("After post-decrement: "+a);
		System.out.println("Post-decrement: "+(a--));
		System.out.println("After post-decrement: "+a);
		System.out.println("Final Value: "+a);



	}

}
